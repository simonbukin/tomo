// ts-to-zod reads one file at a time and turns a cross-file import into `z.any()`, so the
// generated types are first flattened into one input file, which is deleted afterwards.
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const GENERATED = new URL("../src/generated/", import.meta.url).pathname;
const INPUT = join(GENERATED, "wire.ts");
const OUTPUT = new URL("../src/schemas.ts", import.meta.url).pathname;
const SKIP = new Set(["index.ts", "wire.ts"]);

const declarations = readdirSync(GENERATED)
  .filter((name) => name.endsWith(".ts") && !SKIP.has(name))
  .sort()
  .flatMap((name) => readFileSync(join(GENERATED, name), "utf8").split("\n").filter((line) => line.trim() && !line.startsWith("import ") && !line.startsWith("//")));

writeFileSync(INPUT, `${declarations.join("\n")}\n`);
try {
  execFileSync("npx", ["ts-to-zod", "src/generated/wire.ts", "src/schemas.ts"], { stdio: "inherit" });
  const schemas = readFileSync(OUTPUT, "utf8")
    .replace('// Generated by ts-to-zod', "// GENERATED from the ts-rs types by scripts/gen-schemas.mjs. DO NOT EDIT.\n// Run: pnpm gen:schemas")
    .replaceAll('from "./generated/wire"', 'from "./generated"');
  writeFileSync(OUTPUT, schemas);
  console.log(`wrote ${OUTPUT}`);
} finally {
  rmSync(INPUT, { force: true });
}
